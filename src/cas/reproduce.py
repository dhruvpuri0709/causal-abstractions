"""``cas reproduce``: sanity checks against Geiger et al. (2024) and a timing of one DAS fit.

1. The handcrafted network of the pyvene tutorial with its known neuron alignment: IIA = 1.
2. Table 1 analogue: a standard (task-trained) hierarchical-equality MLP, |N| = 16, three hidden
   layers; DAS for "both equality relations" at layers 1-3 (our layers 0-2) with k in {1, 2, 8},
   best of 3 rotation seeds.  Geiger et al. report training-set IIA; we report both the
   in-sample (fit-split) and held-out (test-split) IIA.  Also an IIT-trained network.
3. §4.4 analogue: frozen random networks of increasing width, k = N/2, first layer.
4. Wall time of one DAS fit.

Differences from the paper (see docs/code/deviations_from_proposal.md): far fewer DAS training
pairs (default 8192 vs 640K), our step-budget fitting loop, and our stratified pair sampler.
"""

from __future__ import annotations

import time
from pathlib import Path

import numpy as np
import torch
import yaml

from .config import derive_seed
from .das import FitSettings, fit_rotation, pair_activations, predict
from .models import handcrafted_hierarchical_equality
from .pairs import make_split
from .tasks import TASKS, Task
from .train import (iit_accuracy, new_network, task_accuracy, train_iit, train_standard)

GEIGER_TABLE1 = {  # |N| = 16, both equality relations; (k, layer index 0..2) -> IIA
    (1, 0): 0.88, (1, 1): 0.51, (1, 2): 0.50,
    (2, 0): 0.97, (2, 1): 0.54, (2, 2): 0.50,
    (8, 0): 1.00, (8, 1): 0.57, (8, 2): 0.50,
}
GEIGER_RANDOM = {16: 0.50, 64: 0.50, 256: 0.51, 1028: 0.55, 1024: 0.55, 4096: 0.64}
HYP = "both_equality"


def _acts(model, layer, sp, device):
    return pair_activations(model, layer, torch.tensor(sp.base_x, device=device),
                            torch.tensor(sp.src_x, device=device), sp.pair_base, sp.pair_src,
                            sp.labels[HYP])


def das_grid(model, task, layers, ks, n_seeds, n_fit, n_test, settings, seed, device, tag):
    """Best-of-seeds in-sample and held-out IIA for every (layer, k); also mean and times."""
    rng = np.random.default_rng(derive_seed(seed, tag, "pairs"))
    fit = make_split(task, HYP, n_fit, rng)
    test = make_split(task, HYP, n_test, rng)
    rows = []
    for layer in layers:
        af, at = _acts(model, layer, fit, device), _acts(model, layer, test, device)
        for k in ks:
            ins, outs, secs, steps = [], [], [], []
            for s in range(n_seeds):
                res = fit_rotation(model, layer, k, af,
                                   derive_seed(seed, tag, layer, k, s), settings)
                ins.append((predict(model, layer, af, res.R, k) == fit.labels[HYP]).mean())
                outs.append((predict(model, layer, at, res.R, k) == test.labels[HYP]).mean())
                secs.append(res.seconds)
                steps.append(res.steps)
            b = int(np.argmax(ins))
            rows.append({"layer": layer, "k": k, "best_in_sample": ins[b],
                         "held_out_of_best": outs[b], "best_held_out": max(outs),
                         "mean_in_sample": float(np.mean(ins)), "seconds_per_fit":
                         float(np.mean(secs)), "steps_per_fit": float(np.mean(steps))})
            print(f"  {tag} layer {layer} k {k}: in-sample {ins[b]:.3f} held-out {outs[b]:.3f}"
                  f" ({np.mean(secs):.1f} s/fit)", flush=True)
    return rows


def _table(rows, cols, fmt=".3f"):
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for r in rows:
        lines.append("| " + " | ".join(format(r[c], fmt) if isinstance(r[c], float)
                                        else str(r[c]) for c in cols) + " |")
    return "\n".join(lines) + "\n"


def reproduce(config_path: str, device: str = "cpu", widths: str | None = None) -> Path:
    cfg = yaml.safe_load(Path(config_path).read_text())
    seed = cfg["seed"]
    out = Path(cfg.get("results_dir", "results")) / cfg.get("name", "reproduce")
    out.mkdir(parents=True, exist_ok=True)
    he = TASKS["hierarchical_equality"]
    tr, rd = cfg["trained"], cfg["random"]
    if widths:
        rd["widths"] = [int(w) for w in widths.split(",")]
    t_start = time.perf_counter()
    report = ["# Reproduction of Geiger et al. (2024) checks\n",
              f"Config: `{config_path}`, device `{device}`, torch threads "
              f"{torch.get_num_threads()}. Generated by `cas reproduce` on "
              f"{time.strftime('%Y-%m-%d %H:%M')}.\n"]

    # 1. handcrafted network
    print("1. handcrafted network, known alignment")
    he2 = Task("hierarchical_equality", "he", 4, (HYP,), emb_dim=2)
    hc = handcrafted_hierarchical_equality()
    sp = make_split(he2, HYP, 4096, np.random.default_rng(derive_seed(seed, "handcrafted")))
    iia_hc = float((predict(hc, 0, _acts(hc, 0, sp, "cpu"), None, 4) == sp.labels[HYP]).mean())
    report.append("\n## 1. Handcrafted network (pyvene tutorial)\n\n"
                  f"Neuron alignment WX = neurons 0-3, YZ = neurons 4-7 of layer 0, 4096 pairs: "
                  f"**IIA = {iia_hc:.4f}** (expected 1.0).\n")

    # 2. trained networks
    settings = FitSettings(**cfg["fit"])
    report.append("\n## 2. Trained hierarchical-equality MLP (Table 1 analogue)\n\n"
                  f"Width {tr['width']}, {tr['n_layers']} hidden layers, 4-dim objects; DAS with "
                  f"{tr['n_fit']} fitting pairs and {tr['n_test']} held-out test pairs, best of "
                  f"{tr['seeds']} rotation seeds (chosen by in-sample IIA, as in the paper). "
                  "`geiger` is Table 1 (training-set IIA, best of 3 seeds, |N| = 16). "
                  "Layer indices are 0-based (paper's Layer 1 = our layer 0).\n")
    for kind in ("standard", "iit"):
        print(f"2. {kind} network")
        nseed = derive_seed(seed, "net", kind)
        model = new_network(he, tr["width"], tr["n_layers"], nseed).to(device)
        rng = np.random.default_rng(nseed)
        t0 = time.perf_counter()
        if kind == "standard":
            info = train_standard(model, he, rng, cfg["train"]["standard"], device)
        else:
            info = train_iit(model, he, HYP, tr["iit_layer"], tr["iit_k"], rng,
                             cfg["train"]["iit"], device)
        for p in model.parameters():
            p.requires_grad_(False)
        acc = task_accuracy(model, he, 10000, np.random.default_rng(1), device)
        rows = das_grid(model, he, tr["layers"], tr["ks"], tr["seeds"], tr["n_fit"],
                        tr["n_test"], settings, seed, device, f"trained-{kind}")
        for r in rows:
            r["geiger"] = GEIGER_TABLE1.get((r["k"], r["layer"]), float("nan"))
        extra = ""
        if kind == "iit":
            niia = iit_accuracy(model, he, HYP, tr["iit_layer"], tr["iit_k"], 10000,
                                np.random.default_rng(2), device)
            extra = (f" IIT site: layer {tr['iit_layer']}, k* = {tr['iit_k']}; neuron-aligned "
                     f"IIA at the site = {niia:.4f}.")
        report.append(f"\n### {kind} network\n\nTrained {info['steps']} steps in "
                      f"{time.perf_counter() - t0:.1f} s; held-out task accuracy "
                      f"{acc:.4f}.{extra}\n\n")
        report.append(_table(rows, ["layer", "k", "best_in_sample", "held_out_of_best",
                                    "mean_in_sample", "geiger", "seconds_per_fit"]))

    # 2b. seed-to-seed variation of standard networks at the paper's best site
    n_extra = tr.get("standard_seeds", 0)
    if n_extra:
        print(f"2b. {n_extra} more standard networks (layer 0, k = 8)")
        vrows = []
        for i in range(n_extra):
            nseed = derive_seed(seed, "net", "standard-variation", i)
            model = new_network(he, tr["width"], tr["n_layers"], nseed).to(device)
            info = train_standard(model, he, np.random.default_rng(nseed),
                                  cfg["train"]["standard"], device)
            for p in model.parameters():
                p.requires_grad_(False)
            acc = task_accuracy(model, he, 10000, np.random.default_rng(1), device)
            r = das_grid(model, he, [0], [8], tr["seeds"], tr["n_fit"], tr["n_test"],
                         settings, seed, device, f"variation-{i}")[0]
            vrows.append({"network": i, "train_steps": info["steps"], "task_acc": acc,
                          "best_in_sample": r["best_in_sample"],
                          "held_out_of_best": r["held_out_of_best"]})
        vals = [r["best_in_sample"] for r in vrows]
        report.append(f"\n### Seed-to-seed variation: {n_extra} more standard networks, layer 0, "
                      f"k = 8 (paper: 1.00)\n\n")
        report.append(_table(vrows, ["network", "train_steps", "task_acc", "best_in_sample",
                                     "held_out_of_best"]))
        report.append(f"\nRange of best in-sample IIA: {min(vals):.3f}-{max(vals):.3f}. "
                      "Task-trained networks in this setup do **not** reliably reach the "
                      "near-perfect IIA of Table 1; training 20 000 steps (to 0.9998 accuracy) "
                      "or fitting DAS on 65 536 pairs did not change this in our checks "
                      "(see docs/code/running.md). IIT-trained networks do.\n")

    # 3. random networks
    report.append("\n## 3. Frozen random networks (§4.4 analogue)\n\n"
                  f"Hierarchical equality, 16-dim input, 3 hidden layers of width N, never "
                  f"trained; DAS at layer 0 with k = N/2, {rd['n_fit']} fitting pairs, best of "
                  f"{rd['seeds']} seeds by in-sample IIA. `geiger` is the §4.4 table "
                  "(training-set IIA; the paper lists 1028, presumably 1024).\n\n")
    rsettings = FitSettings(**(cfg["fit"] | rd.get("fit", {})))
    rrows = []
    for w in rd["widths"]:
        print(f"3. random network width {w}")
        model = new_network(he, w, 3, derive_seed(seed, "random", w)).to(device)
        for p in model.parameters():
            p.requires_grad_(False)
        acc = task_accuracy(model, he, 10000, np.random.default_rng(3), device)
        r = das_grid(model, he, [0], [w // 2], rd["seeds"], rd["n_fit"], rd["n_test"],
                     rsettings, seed, device, f"random-{w}")[0]
        rrows.append({"N": w, "k": w // 2, "task_acc": acc, **{c: r[c] for c in (
            "best_in_sample", "held_out_of_best", "mean_in_sample", "seconds_per_fit",
            "steps_per_fit")}, "geiger": GEIGER_RANDOM.get(w, float("nan"))})
    report.append(_table(rrows, ["N", "k", "task_acc", "best_in_sample", "held_out_of_best",
                                 "mean_in_sample", "geiger", "seconds_per_fit",
                                 "steps_per_fit"]))
    report.append("\nWidth 1024 is slow on CPU (each step re-parametrizes a 1024x1024 orthogonal "
                  "matrix) and 4096 is impractical here; pass `--widths 16,64,256,1024` to add "
                  "it.\n")

    # 4. timing
    print("4. timing one fit")
    model = new_network(he, tr["width"], tr["n_layers"], derive_seed(seed, "net", "standard"))
    train_standard(model, he, np.random.default_rng(derive_seed(seed, "net", "standard")),
                   cfg["train"]["standard"], "cpu")
    for p in model.parameters():
        p.requires_grad_(False)
    sp = make_split(he, HYP, tr["n_fit"], np.random.default_rng(5))
    acts = _acts(model, 0, sp, "cpu")
    t0 = time.perf_counter()
    res = fit_rotation(model, 0, 8, acts, 11, settings)
    secs = time.perf_counter() - t0
    report.append(f"\n## 4. Timing\n\nOne DAS fit (width {tr['width']}, layer 0, k = 8, "
                  f"{tr['n_fit']} fitting pairs, batch {settings.batch_size}, lr {settings.lr}): "
                  f"**{secs:.2f} s** wall time for {res.steps} steps "
                  f"({1000 * secs / res.steps:.2f} ms/step; stop reason: {res.stop_reason}). "
                  f"Whole `cas reproduce` run: {time.perf_counter() - t_start:.0f} s.\n")
    path = out / "report.md"
    path.write_text("".join(report))
    print(f"report written to {path}")
    return path
